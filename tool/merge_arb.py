#!/usr/bin/env python3
"""Merge per-module ARB fragments into the gen-l10n input files.

Input : lib/l10n/fragments/<prefix>.bn.arb and <prefix>.en.arb (committed, one
        pair per owning module, see docs/council/04-plan.md section 2.8).
Output: lib/l10n/arb/app_bn.arb (template, @@locale bn) and app_en.arb
        (gitignored, regenerated by tool/ci_prepare.sh before `flutter pub get`).

The script fails (exit 1) and lists every problem it finds when:
  * a fragment is not valid JSON (or not a JSON object, or has a duplicate key
    inside one file),
  * a fragment file name is not <prefix>.<bn|en>.arb or a pair is incomplete,
  * a key is defined by two fragments (duplicate key),
  * a key does not match ^<prefix>[A-Z][A-Za-z0-9]*$ (wrong prefix),
  * the bn and en fragments of one prefix have different key sets,
  * a bn key has no @key entry with a non-empty "description",
  * placeholders differ: text vs bn @key.placeholders, bn vs en, a placeholder
    is not "type": "String", or a name is not ASCII lowerCamelCase,
  * a message contains a literal { or } that is not a simple {placeholder}
    (this also rejects ICU plural/select),
  * a value is not a non-empty string, an @key has no matching key, or
    @@locale disagrees with the file name.

Usage: python3 tool/merge_arb.py [--fragments DIR] [--out DIR] [--check]
  --check  validate only, write nothing.
Standard library only; Python 3.8+.
"""

from __future__ import annotations

import argparse
import json
import os
import re
import sys
from collections import OrderedDict

LOCALES = ("bn", "en")
TEMPLATE_LOCALE = "bn"
FILE_RE = re.compile(r"^([a-z][a-z0-9]*)\.(bn|en)\.arb$")
PLACEHOLDER_NAME_RE = re.compile(r"^[a-z][A-Za-z0-9]*$")
# A placeholder reference inside a message: {name}. Anything else with braces is rejected.
BRACE_TOKEN_RE = re.compile(r"\{([^{}]*)\}")

IN_GITHUB = os.environ.get("GITHUB_ACTIONS") == "true"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def _display(path: str) -> str:
    """Repo-relative, forward-slash path when possible (clickable in CI annotations)."""
    try:
        rel = os.path.relpath(path, ROOT)
    except ValueError:  # different drive on Windows
        return path.replace(os.sep, "/")
    if rel.startswith(".."):
        return path.replace(os.sep, "/")
    return rel.replace(os.sep, "/")


class Problems:
    def __init__(self) -> None:
        self.items: list[tuple[str, str]] = []

    def add(self, path: str, message: str) -> None:
        self.items.append((path, message))

    def __bool__(self) -> bool:
        return bool(self.items)

    def report(self) -> None:
        for raw_path, message in self.items:
            path = _display(raw_path)
            if IN_GITHUB:
                print(f"::error file={path},title=merge_arb::{message}")
            print(f"ERROR {path}: {message}", file=sys.stderr)


def _no_duplicate_object(pairs):
    seen = OrderedDict()
    dups = []
    for key, value in pairs:
        if key in seen:
            dups.append(key)
        seen[key] = value
    if dups:
        raise ValueError("duplicate key(s) inside this file: " + ", ".join(sorted(set(dups))))
    return seen


def load_json(path: str, problems: Problems):
    try:
        with open(path, "r", encoding="utf-8-sig") as fh:
            text = fh.read()
    except OSError as exc:
        problems.add(path, f"cannot read file: {exc}")
        return None
    try:
        data = json.loads(text, object_pairs_hook=_no_duplicate_object)
    except ValueError as exc:  # json.JSONDecodeError is a ValueError subclass
        problems.add(path, f"invalid JSON: {exc}")
        return None
    if not isinstance(data, dict):
        problems.add(path, "top level must be a JSON object")
        return None
    return data


def message_placeholders(path: str, key: str, text: str, problems: Problems) -> set[str] | None:
    """Return the set of {placeholder} names used in text, or None if text is malformed."""
    names: set[str] = set()
    ok = True
    for match in BRACE_TOKEN_RE.finditer(text):
        name = match.group(1)
        if not PLACEHOLDER_NAME_RE.match(name):
            problems.add(
                path,
                f'"{key}": "{{{name}}}" is not a simple placeholder (ASCII lowerCamelCase only; '
                "no ICU plural/select, no literal braces)",
            )
            ok = False
        else:
            names.add(name)
    leftover = BRACE_TOKEN_RE.sub("", text)
    if "{" in leftover or "}" in leftover:
        problems.add(
            path,
            f'"{key}": nested or unbalanced "{{" / "}}" in message (ICU plural/select and literal braces '
            "are not allowed; pre-format with AppFormat and pass a String placeholder)",
        )
        ok = False
    return names if ok else None


def check_fragment(path: str, prefix: str, locale: str, data: dict, problems: Problems):
    """Validate one fragment. Returns (messages, metadata) ordered dicts."""
    messages: "OrderedDict[str, str]" = OrderedDict()
    metadata: "OrderedDict[str, dict]" = OrderedDict()
    key_re = re.compile(r"^" + re.escape(prefix) + r"[A-Z][A-Za-z0-9]*$")

    for key, value in data.items():
        if key == "@@locale":
            if value != locale:
                problems.add(path, f'"@@locale" is {value!r} but the file name says {locale!r}')
            continue
        if key.startswith("@@"):
            continue  # other global attributes (@@context etc.) are dropped
        if key.startswith("@"):
            base = key[1:]
            if not isinstance(value, dict):
                problems.add(path, f'"{key}" must be a JSON object')
                continue
            metadata[base] = value
            continue
        if not key_re.match(key):
            problems.add(path, f'key "{key}" must match ^{prefix}[A-Z][A-Za-z0-9]*$ (wrong prefix or characters)')
            continue
        if not isinstance(value, str) or value.strip() == "":
            problems.add(path, f'"{key}" must be a non-empty string')
            continue
        messages[key] = value

    for base in metadata:
        if base not in messages and key_re.match(base):
            problems.add(path, f'"@{base}" has no matching "{base}" message')
        elif base not in messages:
            problems.add(path, f'"@{base}" has no matching message (and "{base}" has the wrong prefix)')

    return messages, metadata


def declared_placeholders(path: str, key: str, meta: dict, problems: Problems) -> set[str] | None:
    raw = meta.get("placeholders", {})
    if raw is None:
        raw = {}
    if not isinstance(raw, dict):
        problems.add(path, f'"@{key}.placeholders" must be an object')
        return None
    ok = True
    for name, spec in raw.items():
        if not PLACEHOLDER_NAME_RE.match(name):
            problems.add(path, f'"@{key}": placeholder name "{name}" must be ASCII lowerCamelCase')
            ok = False
        if not isinstance(spec, dict) or spec.get("type") != "String":
            problems.add(path, f'"@{key}": placeholder "{name}" must declare "type": "String"')
            ok = False
    return set(raw) if ok else None


def main(argv: list[str]) -> int:
    root = ROOT
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--fragments", default=os.path.join(root, "lib", "l10n", "fragments"))
    parser.add_argument("--out", default=os.path.join(root, "lib", "l10n", "arb"))
    parser.add_argument("--check", action="store_true", help="validate only, do not write output")
    args = parser.parse_args(argv)

    problems = Problems()
    frag_dir = args.fragments
    if not os.path.isdir(frag_dir):
        problems.add(frag_dir, "fragments directory not found")
        problems.report()
        return 1

    pairs: dict[str, dict[str, str]] = {}
    for name in sorted(os.listdir(frag_dir)):
        path = os.path.join(frag_dir, name)
        if os.path.isdir(path):
            problems.add(path, "unexpected directory in fragments/")
            continue
        m = FILE_RE.match(name)
        if not m:
            problems.add(path, "file name must be <prefix>.bn.arb or <prefix>.en.arb (prefix: lowercase ASCII)")
            continue
        pairs.setdefault(m.group(1), {})[m.group(2)] = path

    if not pairs:
        problems.add(frag_dir, "no ARB fragments found")

    merged: dict[str, "OrderedDict[str, object]"] = {
        loc: OrderedDict([("@@locale", loc)]) for loc in LOCALES
    }
    owner: dict[str, str] = {}  # key -> fragment path that defined it (bn side)

    for prefix in sorted(pairs):
        files = pairs[prefix]
        missing = [loc for loc in LOCALES if loc not in files]
        for loc in missing:
            other = next(iter(files.values()))
            problems.add(other, f"missing partner fragment {prefix}.{loc}.arb")
        if missing:
            continue

        loaded = {loc: load_json(files[loc], problems) for loc in LOCALES}
        if any(v is None for v in loaded.values()):
            continue

        checked = {
            loc: check_fragment(files[loc], prefix, loc, loaded[loc], problems) for loc in LOCALES
        }
        bn_msgs, bn_meta = checked["bn"]
        en_msgs, _en_meta = checked["en"]

        only_bn = [k for k in bn_msgs if k not in en_msgs]
        only_en = [k for k in en_msgs if k not in bn_msgs]
        for k in only_bn:
            problems.add(files["en"], f'key "{k}" exists in bn but not in en')
        for k in only_en:
            problems.add(files["bn"], f'key "{k}" exists in en but not in bn')

        for key, bn_text in bn_msgs.items():
            if key in owner:
                problems.add(files["bn"], f'duplicate key "{key}" (already defined in {owner[key]})')
                continue
            owner[key] = files["bn"]

            meta = bn_meta.get(key)
            if meta is None:
                problems.add(files["bn"], f'"{key}" has no "@{key}" entry (description required)')
                continue
            desc = meta.get("description")
            if not isinstance(desc, str) or not desc.strip():
                problems.add(files["bn"], f'"@{key}.description" is missing or empty')

            declared = declared_placeholders(files["bn"], key, meta, problems)
            used_bn = message_placeholders(files["bn"], key, bn_text, problems)
            if declared is not None and used_bn is not None and declared != used_bn:
                problems.add(
                    files["bn"],
                    f'"{key}": placeholders in text {sorted(used_bn)} != declared in @{key} {sorted(declared)}',
                )
            if key in en_msgs:
                used_en = message_placeholders(files["en"], key, en_msgs[key], problems)
                reference = declared if declared is not None else used_bn
                if used_en is not None and reference is not None and used_en != reference:
                    problems.add(
                        files["en"],
                        f'"{key}": placeholders {sorted(used_en)} differ from bn {sorted(reference)}',
                    )

            out_meta = OrderedDict()
            out_meta["description"] = desc if isinstance(desc, str) else ""
            if meta.get("placeholders"):
                out_meta["placeholders"] = meta["placeholders"]
            merged["bn"][key] = bn_text
            merged["bn"]["@" + key] = out_meta
            if key in en_msgs:
                merged["en"][key] = en_msgs[key]

    if problems:
        problems.report()
        print(f"merge_arb: {len(problems.items)} problem(s); nothing written.", file=sys.stderr)
        return 1

    count = len(owner)
    if args.check:
        print(f"merge_arb: OK, {count} keys in {len(pairs)} fragment pair(s) (check only).")
        return 0

    os.makedirs(args.out, exist_ok=True)
    for loc in LOCALES:
        out_path = os.path.join(args.out, f"app_{loc}.arb")
        payload = json.dumps(merged[loc], ensure_ascii=False, indent=2) + "\n"
        with open(out_path, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(payload)
    print(f"merge_arb: wrote {count} keys from {len(pairs)} fragment pair(s) to {_display(args.out)}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
